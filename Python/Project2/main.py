def run_quiz(topic_name, questions):
    """
    選ばれたテーマのクイズを実行し、正解数と出題数を返す関数。
    """
    print(f"\n{'='*30}")
    print(f" {topic_name} のクイズを開始します！")
    print(f"{'='*30}")
    
    score = 0
    total_questions = len(questions)

    for i, q in enumerate(questions):
        print(f"\n【第{i+1}問】 {q['q']}")
        
        # 選択肢を出力する
        for choice in q['options']:
            print(f"  {choice}")

        while True:
            # ユーザに入力を促すガイドを表示
            ans = input("▶ 解答を1〜4で入力してください（クイズをやめる場合は 'q' を入力）: ")

            # while文などを先取りで自習し、クイズを途中で辞める機能
            if ans.lower() == 'q':
                print("\nクイズを中断しました。お疲れ様でした！")
                return score, i + 1 # 中断した時点でのスコアと挑戦した問題数を返す

            # 入力が1〜4のいずれかであるか判定
            if ans in ['1', '2', '3', '4']:
                # 正解・不正解を判定するプログラム
                if ans == q['ans']:
                    print("⭕ 正解です！素晴らしい！")
                    score += 1
                else:
                    print(f"❌ 不正解... (正解は {q['ans']} 番でした)")
                break # 入力が正しかったので、次の問題へ進む
            else:
                # 存在しない選択肢を入力された際に、再入力を求める仕組み
                print("⚠️ 無効な入力です。1, 2, 3, 4 または q を入力してください。")

    return score, total_questions

def main():
    """
    プログラムのメイン処理を行う関数。
    """
    print("\n★★★ 選択式クイズアプリへようこそ！ ★★★")
    quiz_data = get_quiz_data()

    while True:
        print("\n挑戦したいクイズのジャンルを選んでください。")
        for key, value in quiz_data.items():
            print(f" {key}: {value['name']}")
        print(" q: アプリを終了する")

        # ユーザに入力を促すガイドを表示
        choice = input("\n▶ ジャンルを番号で入力してください: ")

        if choice.lower() == 'q':
            print("アプリを終了します。遊んでくれてありがとう！")
            break

        # 入力された番号が辞書の中に存在するかチェック
        if choice in quiz_data:
            topic = quiz_data[choice]["name"]
            questions = quiz_data[choice]["questions"]
            
            # クイズを実行
            score, answered = run_quiz(topic, questions)

            # 複数のクイズが実装されている場合、正解の数(得点)が最後に出力される
            print("\n" + "="*30)
            print(f"【最終結果】 {answered}問中、{score}問正解しました！")
            print("="*30)
        else:
            # 存在しないジャンルを入力された際の再入力要求
            print("⚠️ 無効な入力です。メニューにある番号を入力してください。")

if __name__ == "__main__":
    main()